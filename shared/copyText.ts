/**
 * Copy text to the clipboard; resolves true when it worked.
 *
 * navigator.clipboard is missing on plain http and can refuse permission, and
 * the copy buttons called it with no catch — the click did nothing and threw.
 * This falls back to a hidden textarea and execCommand, and never throws.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch { /* fall through to the textarea */ }
  try {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', '');
    area.style.position = 'fixed';
    area.style.opacity = '0';
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(area);
    return ok;
  } catch {
    return false;
  }
}
